import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){try{return next(specifier,context)}catch(error){if(specifier.startsWith('.')&&!/\.[a-z]+$/.test(specifier))return next(specifier+'.ts',context);throw error}}});
const {seed}=await import('../app/content.ts');
const {integrateClubContent}=await import('../app/club-integration.ts');
const {scheduledResults,saveScheduledResult}=await import('../app/scheduled-results.ts');
const {saveLeagueResult}=await import('../app/league-results.ts');
const {contentSchema}=await import('../app/validation.ts');
const fixture={id:'academy-game',date:'2026-11-01',season:'2026/27',time:'15:00',team:'Senior',competition:'League',competitionId:'league',opponent:'Rovers',venue:'Ground',homeAway:'away',status:'scheduled',goalsFor:null,goalsAgainst:null};
let c=integrateClubContent({...seed,competitions:[{id:'league',name:'League',kind:'league'}],fixtures:[fixture],leagueSchedules:[{competitionId:'league',competition:'League',season:'2026/27',fixtures:[{number:1,date:fixture.date,home:'Rovers',away:seed.name,venue:'Ground',round:'Week 1',time:'15:00'},{number:2,date:fixture.date,home:'United',away:'City',venue:'Ground',round:'Week 1',time:'15:00'}]}]});
assert.equal(scheduledResults(c).length,2,'Academy schedule entry is not duplicated');
let other=()=>scheduledResults(c).find(r=>r.home==='United');
const club=name=>c.standings.find(r=>r.club===name);
assert.equal(other().homeGoals,null,'Unplayed score stays blank');
assert.throws(()=>saveScheduledResult(c,other(),NaN,0));
assert.throws(()=>saveScheduledResult(c,other(),1.5,0));
c=saveScheduledResult(c,other(),2,1);
assert.equal(club('United').points,3);assert.equal(club('City').lost,1);
c=saveScheduledResult(c,other(),0,0);
assert.equal(club('United').played,1);assert.equal(club('United').points,1);assert.equal(club('City').points,1);
c=integrateClubContent(contentSchema.parse(c));
assert.equal(other().homeGoals,0);assert.equal(club('United').played,1);
c=saveLeagueResult(c,other().resultId);
assert.equal(club('United').played,0);assert.equal(other().homeGoals,null);
const own=()=>scheduledResults(c).find(r=>r.fixtureId);
c=saveScheduledResult(c,own(),1,3);
assert.equal(c.fixtures[0].goalsFor,3);assert.equal(c.fixtures[0].goalsAgainst,1);assert.equal(c.fixtures[0].status,'played');assert.equal(club(seed.name).points,3);
c=integrateClubContent({...c,fixtures:c.fixtures.map(f=>({...f,goalsFor:1}))});
assert.equal(own().awayGoals,1);assert.equal(club(seed.name).points,1);assert.equal(club(seed.name).played,1);
assert.equal(contentSchema.safeParse(c).success,true);
console.log('PASS: schedule score entry, blanks, corrections, draws, clearing, persistence, academy away scores and shared fixture updates.');
