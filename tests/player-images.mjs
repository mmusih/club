import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){try{return next(specifier,context)}catch(error){if(specifier.startsWith('.')&&!/\.[a-z]+$/.test(specifier))return next(specifier+'.ts',context);throw error}}});
const {playerSchema,newPlayer,publicPlayer}=await import('../app/player-model.ts');
const profile={...newPlayer(),name:'Demo Player',ageGroup:'Senior',photo:'https://example.com/profile.jpg',headshot:'https://example.com/headshot.jpg'};
const parsed=playerSchema.parse(profile);
assert.equal(parsed.photo,profile.photo);
assert.equal(parsed.headshot,profile.headshot);
assert.equal(playerSchema.parse({...profile,headshot:''}).photo,profile.photo,'Removing a headshot must preserve the profile photo');
assert.equal(playerSchema.parse({...profile,photo:''}).headshot,profile.headshot,'Removing a profile photo must preserve the headshot');
const {headshot,...legacy}=profile;void headshot;
const migrated=playerSchema.parse(legacy);
assert.equal(migrated.photo,profile.photo);
assert.equal(migrated.headshot,undefined,'Do not repurpose an existing profile photo as a headshot');
assert.equal(playerSchema.safeParse({...profile,headshot:'javascript:alert(1)'}).success,false);
assert.equal(playerSchema.safeParse({...profile,headshot:'/media/abc-123.webp'}).success,true);
const publicRecord=publicPlayer({...profile,...parsed});
assert.equal(publicRecord.photo,profile.photo);assert.equal(publicRecord.headshot,profile.headshot);
assert.equal('dateOfBirth' in publicRecord,false);assert.equal('consent' in publicRecord,false);
console.log('PASS: independent profile/headshot storage, independent removal, legacy profiles, upload URL validation and public projection.');
