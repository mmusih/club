import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){try{return next(specifier,context)}catch(error){if(specifier.startsWith('.')&&!/\.[a-z]+$/.test(specifier))return next(specifier+'.ts',context);throw error}}});
const {seed}=await import('../app/content.ts');
const {recordPlayerEvent,replayMatch,fixturePlayerMatches,tacticalPlayerHistory}=await import('../app/match-record.ts');
const {snapshotMatchPlayers,matchSheetRows}=await import('../app/match-sheet.ts');
const {publicContent}=await import('../app/lineup.ts');
const {saveLeagueResult}=await import('../app/league-results.ts');
const {contentSchema}=await import('../app/validation.ts');
let match={phase:'live',minute:75,duration:90,period:'second',slots:['starter'],bench:['sub'],events:[]};
match=recordPlayerEvent(match,{id:'change',kind:'substitution',minute:78,playerId:'starter',replacementId:'sub'});
match=recordPlayerEvent(match,{id:'goal',kind:'goal',minute:81,playerId:'sub'});
match={...match,minute:90,phase:'finished'};
assert.deepEqual(match.slots,['starter']);assert.deepEqual(match.bench,['sub']);
assert.deepEqual(replayMatch(match).minutes,{starter:78,sub:12});
const tactical=tacticalPlayerHistory(match);
assert.deepEqual(tactical[0].map(p=>p.playerId),['starter','sub']);
assert.equal(tactical[0][0].exited.minute,78);
assert.equal(tactical[0][1].entered.minute,78);
assert.equal(tactical[0][1].exited,undefined);
const chain={...match,slots:['starter','other'],bench:['sub','second'],events:[...match.events,{id:'second-change',kind:'substitution',minute:85,playerId:'sub',replacementId:'second'},{id:'move',kind:'position',minute:86,playerId:'second',slotIndex:1}]};
assert.deepEqual(tacticalPlayerHistory(chain)[1].map(p=>p.playerId),['starter','sub','second']);
assert.equal(tacticalPlayerHistory(chain)[1][1].exited.minute,85);
assert.deepEqual(tacticalPlayerHistory({...match,minute:77})[0].map(p=>p.playerId),['starter']);
assert.throws(()=>recordPlayerEvent(match,{id:'early',kind:'goal',minute:77,playerId:'sub'}));
assert.throws(()=>recordPlayerEvent(match,{id:'late',kind:'goal',minute:81,playerId:'starter'}));
const players=[{id:'starter',name:'Original player',number:4,maId:'private',dateOfBirth:''},{id:'sub',name:'Incoming player',number:12,maId:'private',dateOfBirth:''}];
let fixture={id:'game',date:'2026-10-01',time:'12:00',status:'played',team:'Senior',opponent:'Other',match,lineup:{formation:'2-2',starters:['Incorrect overwritten name'],substitutes:[]}};
fixture=snapshotMatchPlayers({...seed,fixtures:[fixture]},seed,players).fixtures[0];
assert.deepEqual(fixture.lineup.starters,['4 Original player']);assert.deepEqual(fixture.lineup.substitutes,['12 Incoming player']);
assert.equal(fixturePlayerMatches([fixture],'sub')[0].goals,1);
const sheet=matchSheetRows(fixture,players);assert.equal(sheet.starters[0].out,"78'");assert.equal(sheet.substitutes[0].in,"78'");assert.equal(sheet.substitutes[0].goals,"81'");
const visible=publicContent({...seed,fixtures:[fixture]},Date.parse('2026-10-02')).fixtures[0];
assert.equal(visible.match,undefined);assert.equal(JSON.stringify(visible).includes('private'),false);
assert.deepEqual(visible.lineup.timeline.map(e=>[e.kind,e.time,e.player,e.incoming]),[['substitution','78′','4 Original player','12 Incoming player'],['goal','81′','12 Incoming player',undefined]]);
assert.equal(publicContent({...seed,fixtures:[fixture]},Date.parse('2026-09-01')).fixtures[0].lineup,undefined);
const row={season:'2026/27',competition:'League',group:'Senior',position:1,played:0,won:0,drawn:0,lost:0,goalsFor:0,goalsAgainst:0,points:0};
const original={...seed,standings:[{...row,id:'a',club:'Rovers',points:-2},{...row,id:'b',club:'Wanderers'}]};
const result={id:'r',date:'2026-10-01',homeId:'a',awayId:'b',homeGoals:2,awayGoals:1};
let c=saveLeagueResult(original,'r',result);
assert.equal(c.standings[0].points,1);assert.equal(c.standings[1].lost,1);assert.equal(contentSchema.safeParse(c).success,true);
c=saveLeagueResult(c,'r',{...result,homeGoals:1});
assert.equal(c.standings[0].played,1);assert.equal(c.standings[0].won,0);assert.equal(c.standings[0].drawn,1);assert.equal(c.standings[0].points,-1);assert.equal(c.standings[1].points,1);
assert.throws(()=>saveLeagueResult(c,'duplicate',{...result,id:'duplicate'}));
assert.throws(()=>saveLeagueResult(c,'bad',{...result,id:'bad',awayId:'a'}));
assert.equal(contentSchema.safeParse({...c,standings:c.standings.slice(1)}).success,false);
assert.deepEqual(saveLeagueResult(c,'r').standings,original.standings);
assert.deepEqual(saveLeagueResult(c,'r',{...result,homeGoals:1}).standings,c.standings);
console.log('PASS: 78-minute substitution, 81-minute goal, original lineup persistence, timed public history, privacy, match sheets, all-club result edits and reversals.');
