import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){try{return next(specifier,context)}catch(error){if(specifier.startsWith('.')&&!/\.[a-z]+$/.test(specifier))return next(specifier+'.ts',context);throw error}}});
const {seed}=await import('../app/content.ts');
const {integrateClubContent}=await import('../app/club-integration.ts');
const {teamKey,teamNames,teamBranding,academyName}=await import('../app/team-branding.ts');
const {prepareFixtureImport}=await import('../app/fixture-import.ts');
const {contentSchema}=await import('../app/validation.ts');
const competition={id:'league',name:'Test League',kind:'league'};
const rows=[{number:1,date:'2026-10-13',home:'EyesOnTheBall',away:'Palapye United FC',venue:'Ground',round:'Week 1'},{number:2,date:'2026-10-14',home:'Palapye United',away:'Rovers',venue:'Ground',round:'Week 1'}];
const c={...seed,name:'EyesOnTheBall',competitions:[competition],teamLogos:[{name:'Palapye United FC',logo:'https://example.com/logo.png'},{name:'Palapye United',logo:''}]};
const imported=prepareFixtureImport(rows,c,'Eyes On The Ball Academy','Senior','league');
const integrated=integrateClubContent({...c,fixtures:imported.fixtures,leagueSchedules:imported.leagueSchedules});
assert.equal(integrated.name,academyName);
assert.equal(integrated.standings.length,3,'Include opponents that never play the academy in this selection');
assert.equal(teamNames(integrated).filter(name=>teamKey(name)===teamKey('Palapye United')).length,1);
assert.equal(teamBranding(integrated).logos[teamKey('Palapye United')],'https://example.com/logo.png');
assert.equal(teamKey('Palapye United F.C.'),teamKey('Palapye United'));
assert.notEqual(teamKey('Palapye City'),teamKey('Palapye United'));
assert.ok(contentSchema.safeParse(integrated).success);
assert.deepEqual(integrateClubContent(integrated),integrated,'Repeated reads must be stable');
const edited={...integrated,standings:integrated.standings.map((r,i)=>i===0?{...r,played:2,won:1,drawn:1,points:4,goalsFor:3,goalsAgainst:1}:r)};
assert.deepEqual(integrateClubContent(edited).standings,edited.standings,'Never overwrite official results');
const repeated=prepareFixtureImport(rows.map(r=>({...r,away:r.away.replace(' FC','')})),integrated,'EyesOnTheBall','Senior','league');
assert.equal(repeated.fixtures.length,0,'FC variants do not create another academy fixture');
const nextSeason={...integrated,leagueSchedules:[...integrated.leagueSchedules,{...integrated.leagueSchedules[0],season:'2027/28'}]};
assert.equal(integrateClubContent(nextSeason).standings.length,6,'Seasons remain independent');
const cup={...seed,competitions:[{...competition,kind:'cup'}],fixtures:imported.fixtures};
assert.equal(integrateClubContent(cup).standings.length,0,'Cup fixtures do not generate a league table');
console.log('PASS: complete fixture standings, stable imports, preserved manual results, separate seasons, FC aliases and shared logos.');
